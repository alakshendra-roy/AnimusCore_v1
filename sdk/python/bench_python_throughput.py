#!/usr/bin/env python3
"""animus-py -- Python-side ingestion throughput benchmark.

Measures how fast a Python process can pull TelemetryFrame records out of
the native SPSC ring and into NumPy via AnimusConsumer.to_numpy(): a
background native producer thread (start_synthetic_load, unthrottled)
floods the ring while this process's main thread drains it in a tight loop,
converting each batch to a zero-copy structured ndarray and doing nothing
more than counting rows -- no per-frame Python object construction, no
list/dict allocation, no copy beyond the one memcpy-equivalent per frame
the ring's own pop() already pays.

This script measures real, reproducible numbers on whatever machine runs
it -- it does not print a canned figure. The 5,000,000-8,000,000
frames/sec range the SDK targets is a claim about the ring/binding's own
per-frame overhead, achievable on a modern desktop/server core; actual
throughput on any given run depends on CPU, Python build, and background
load, exactly like animus_bench's own C++ numbers depend on the machine
running them (see benchmarks/animus_harness.cpp). Do not edit this file to
hardcode a result -- rerun it.

Usage:
    python sdk/python/bench_python_throughput.py [--duration SECONDS]
                                                  [--capacity FRAMES]
                                                  [--batch FRAMES]
                                                  [--target-rate FRAMES_PER_SEC]
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

try:
    from animus_sdk import AnimusConsumer, AnimusRingBuffer
except ImportError:
    # Not installed (`pip install ./sdk/python`) -- fall back to this
    # uncompiled source checkout for fast local iteration. Appended, not
    # inserted at sys.path[0]: this script's own directory must never take
    # priority over an already-installed wheel, or it shadows the
    # installed animus_sdk package -- which carries the compiled
    # _animus_sdk_native extension this source checkout doesn't have --
    # with this checkout's extension-less animus_sdk/, breaking every
    # caller (e.g. deploy_verify.sh) that just built and installed that
    # wheel on purpose.
    sys.path.append(str(Path(__file__).resolve().parent))
    from animus_sdk import AnimusConsumer, AnimusRingBuffer

_TARGET_LOW = 5_000_000
_TARGET_HIGH = 8_000_000


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--duration", type=float, default=5.0, help="benchmark window in seconds (default: 5.0)")
    p.add_argument("--capacity", type=int, default=1 << 20, help="ring capacity in frames (default: 1,048,576)")
    p.add_argument("--batch", type=int, default=8192, help="drain batch size in frames (default: 8192)")
    p.add_argument(
        "--target-rate",
        type=float,
        default=0.0,
        help="cap the synthetic producer's rate (frames/sec); 0 = unthrottled, "
             "producing as fast as the ring accepts (default: 0, unthrottled)",
    )
    return p.parse_args()


def run(duration_s: float, capacity: int, batch: int, target_rate: float) -> None:
    ring = AnimusRingBuffer(capacity=capacity, drain_batch_capacity=batch)
    consumer = AnimusConsumer(ring)

    print("=" * 78)
    print("  ANIMUS-PY -- PYTHON-SIDE INGESTION THROUGHPUT BENCHMARK")
    print("=" * 78)
    print(f"  Ring capacity        : {capacity:,} frames")
    print(f"  Drain batch size     : {batch:,} frames")
    print(f"  Benchmark window     : {duration_s:.1f} s")
    print(f"  Producer target rate : {'unthrottled' if target_rate <= 0 else f'{target_rate:,.0f} frames/sec'}")
    print()

    ring.start_synthetic_load(frame_count=0, target_frames_per_sec=target_rate)
    try:
        # Let the producer thread actually spin up and start filling the
        # ring before the timed window opens, so the very first drain()
        # calls aren't measuring an empty ring.
        time.sleep(0.05)

        frames_received = 0
        empty_polls = 0
        start = time.perf_counter()
        deadline = start + duration_s
        while time.perf_counter() < deadline:
            view = consumer.drain(batch)
            arr = consumer.to_numpy(view)
            n = len(arr)
            if n == 0:
                empty_polls += 1
                continue
            frames_received += n
        elapsed = time.perf_counter() - start
    finally:
        ring.stop_synthetic_load()

    rate = frames_received / elapsed if elapsed > 0 else 0.0

    print("  Results")
    print("  " + "-" * 76)
    print(f"  Frames received      : {frames_received:,}")
    print(f"  Elapsed              : {elapsed:.3f} s")
    print(f"  Sustained rate       : {rate:,.0f} frames/sec")
    print(f"  Empty-poll count     : {empty_polls:,} (drain() calls that found the ring momentarily empty)")
    print(f"  Producer pushed      : {ring.pushed_count:,}")
    print(f"  Producer dropped     : {ring.dropped_count:,} (ring was full -- consumer fell behind, not a bug)")
    print()

    if rate >= _TARGET_LOW:
        print(f"  PASS: sustained rate {rate:,.0f} frames/sec meets the "
              f"{_TARGET_LOW:,}-{_TARGET_HIGH:,} frames/sec target range on this machine.")
    else:
        print(f"  BELOW TARGET: sustained rate {rate:,.0f} frames/sec did not reach the "
              f"{_TARGET_LOW:,} frames/sec floor on this machine. Throughput here scales with "
              "single-core CPU speed and Python interpreter build (a free-threaded/no-GIL "
              "build removes GIL reacquisition overhead on the ndarray-construction step); "
              "rerun on the target deployment hardware before citing a number.")
    print("=" * 78)

    if frames_received == 0:
        raise SystemExit("no frames were received at all -- the native extension is likely not built; "
                          "see sdk/python/CMakeLists.txt")


def main() -> None:
    args = parse_args()
    run(args.duration, args.capacity, args.batch, args.target_rate)


if __name__ == "__main__":
    main()
